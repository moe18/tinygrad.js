#!/usr/bin/env node
// Build dist/: bundle the API, worker and bridge with esbuild, emit .d.ts with tsc, copy pinned wheels.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { PINS } from "./pins.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");

// 1. embed python/tinygrad_js/*.py into the worker bundle
const pyDir = path.join(root, "python");
const files = {};
(function walk(rel) {   // includes tinygrad_js/_shims/torch (the PyTorch-compatible API, see docs/TORCH.md)
  for (const e of fs.readdirSync(path.join(pyDir, rel), { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (e.isDirectory()) { if (e.name !== "__pycache__") walk(`${rel}/${e.name}`); }
    else if (e.name.endsWith(".py")) files[`${rel}/${e.name}`] = fs.readFileSync(path.join(pyDir, rel, e.name), "utf8");
  }
})("tinygrad_js");
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/python.ts"),
  "// GENERATED by scripts/build.mjs from python/tinygrad_js (recursively). Do not edit.\n" +
  `export const PYTHON_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`);

// 2. bundle
fs.rmSync(dist, { recursive: true, force: true });
const common = { bundle: true, format: "esm", target: "es2022", sourcemap: true, logLevel: "warning", legalComments: "inline" };
await esbuild.build({ ...common, entryPoints: { index: "src/index.ts", worker: "src/worker.ts", bridge: "src/bridge.ts", cuda: "src/cuda/index.ts",
  "cuda-worker": "src/cuda/runtime/wasm-worker.ts" }, outdir: dist, absWorkingDir: root, splitting: false });

// 3. type declarations
execFileSync(path.join(root, "node_modules/.bin/tsc"), ["-p", "tsconfig.json", "--emitDeclarationOnly"], { cwd: root, stdio: "inherit" });

// 4. pinned tinygrad wheels (run `npm run fetch:assets` first)
fs.mkdirSync(path.join(dist, "assets"), { recursive: true });
for (const w of PINS.tinygrad) {
  const src = path.join(root, "assets", w.file);
  if (!fs.existsSync(src)) throw new Error(`missing ${path.relative(root, src)}; run \`npm run fetch:assets\``);
  fs.copyFileSync(src, path.join(dist, "assets", w.file));
}
console.log("built dist/");
