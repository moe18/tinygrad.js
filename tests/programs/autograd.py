x = param([2.0])
y = (x * x).sum()
y.backward()
w = param([[0.5, -1.0, 2.0], [1.5, 0.25, -0.75]])
inp = param([[1.0, 2.0], [-1.0, 0.5], [3.0, -2.0], [0.0, 1.0]])
target = Tensor([0, 2, 1, 2])
loss = (inp @ w).sparse_categorical_crossentropy(target)
loss.backward()
z = param([0.1, -0.7, 1.3, 2.2])
(z.sigmoid() * z.exp() + z.tanh() ** 2).sum().backward()
emit(x_grad=x.grad, loss=loss, w_grad=w.grad, inp_grad=inp.grad, z_grad=z.grad)
